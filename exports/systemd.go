package exports

import (
	"errors"
	"io"
	"path/filepath"
	"strings"
	"text/template"
)

// systemdUnit runs one site's server block, from /var/www/<name> so the
// file's relative paths (read(), directory, require) resolve there
var systemdUnit = template.Must(template.New("systemd").Parse(`# rest-{{.Name}}.service, generated by ` + "`rest -f {{.File}} -e systemd{{.Flag}}`" + `
# site files go in /var/www/{{.Name}} (paths in the .rest file are relative to it)
# install:
#   sudo cp rest-{{.Name}}.service /etc/systemd/system/
#   sudo systemctl daemon-reload && sudo systemctl enable --now rest-{{.Name}}
[Unit]
Description=rest server: {{.Name}}
After=network-online.target
Wants=network-online.target

[Service]
WorkingDirectory=/var/www/{{.Name}}
ExecStart=/usr/local/bin/rest -f {{.File}} -s --no-color
Restart=on-failure
RestartSec=2
DynamicUser=yes
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes

[Install]
WantedBy=multi-user.target
`))

// SiteName is the default name for a site: its rest file's name w/o .rest
func SiteName(filename string) string {
	return strings.TrimSuffix(filepath.Base(filename), ".rest")
}

// ToSystemd writes a systemd unit that serves filename's server block as
// rest-<name>.service. An empty name defaults to SiteName(filename).
// flagName is the --name given on the cli (shown in the header comment),
// it takes precedence over name.
func ToSystemd(w io.Writer, filename, name, flagName string) error {
	file := filepath.Base(filename)
	flag := ""
	if flagName != "" {
		name = flagName
		flag = " --name " + flagName
	}
	if name == "" {
		name = SiteName(filename)
	}
	if name == "" || name == "." || strings.ContainsAny(name, "/ \t\n") {
		return errors.New("systemd: invalid site name, set one w/ --name")
	}
	return systemdUnit.Execute(w, struct{ Name, File, Flag string }{name, file, flag})
}
