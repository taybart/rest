package exports

import (
	"io"
	"path/filepath"
	"text/template"
)

// systemdUnit is a template unit (rest@.service): rest@<site> serves the
// server block of the .rest file in /var/www/<site>, from that folder so the
// file's relative paths (read(), directory, require) resolve there
var systemdUnit = template.Must(template.New("systemd").Parse(`# rest@.service, generated by ` + "`rest -e systemd`" + `
# one unit for every site: rest@<site> serves /var/www/<site>, which holds the
# site's files and one .rest file with a server block (paths in it are relative
# to that folder)
# install:
#   sudo cp rest@.service /etc/systemd/system/
#   sudo systemctl daemon-reload
#   sudo systemctl enable --now rest@{{.Site}}
[Unit]
Description=rest server: %i
After=network-online.target
Wants=network-online.target

[Service]
WorkingDirectory=/var/www/%i
ExecStart=/usr/local/bin/rest -s -f . --no-color
Restart=on-failure
RestartSec=2
DynamicUser=yes
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes

[Install]
WantedBy=multi-user.target
`))

// SiteName is the default site (instance) name for a rest file: the name of
// the folder it's in, since that's what /var/www/<site> holds
func SiteName(filename string) string {
	if abs, err := filepath.Abs(filename); err == nil {
		filename = abs
	}
	return filepath.Base(filepath.Dir(filename))
}

// ToSystemd writes the rest@.service template unit, which is the same for
// every site. site is only used in the install comment (rest@<site>).
func ToSystemd(w io.Writer, site string) error {
	if site == "" {
		site = "<site>"
	}
	return systemdUnit.Execute(w, struct{ Site string }{site})
}
