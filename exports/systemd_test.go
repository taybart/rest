package exports_test

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/taybart/rest"
	"github.com/taybart/rest/exports"
)

func writeRest(t *testing.T, name, src string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), name)
	if err := os.WriteFile(p, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

func TestSystemdExport(t *testing.T) {
	p := writeRest(t, "site.com.rest", `server { address = "localhost:8083" }`)
	r, err := rest.NewFile(p)
	if err != nil {
		t.Fatal(err)
	}

	tests := []struct {
		name, want, wantFlag string
	}{
		{"", "site.com", ""},
		{"site.com", "site.com", " --name site.com"},
		{"other", "other", " --name other"},
	}
	for _, tt := range tests {
		var out bytes.Buffer
		if err := r.ExportSystemd(&out, tt.name); err != nil {
			t.Fatal(err)
		}
		got := out.String()
		for _, line := range []string{
			"# rest-" + tt.want + ".service, generated by `rest -f site.com.rest -e systemd" + tt.wantFlag + "`",
			"Description=rest server: " + tt.want,
			"WorkingDirectory=/var/www/" + tt.want,
			"ExecStart=/usr/local/bin/rest -f site.com.rest -s --no-color",
			"enable --now rest-" + tt.want + "\n",
		} {
			if !strings.Contains(got, line) {
				t.Errorf("name %q: missing %q in:\n%s", tt.name, line, got)
			}
		}
	}

	// -e systemd through ExportTo uses the default name
	var out bytes.Buffer
	if err := r.ExportTo(&out, "systemd", "", -1); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out.String(), "WorkingDirectory=/var/www/site.com\n") {
		t.Errorf("ExportTo systemd:\n%s", out.String())
	}

	if err := r.ExportSystemd(&bytes.Buffer{}, "bad/name"); err == nil {
		t.Error("expected an error for a name w/ a slash")
	}
}

func TestSystemdExportServerName(t *testing.T) {
	p := writeRest(t, "site.rest", `server {
  name    = "named.com"
  address = "localhost:8083"
}`)
	r, err := rest.NewFile(p)
	if err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer
	if err := r.ExportSystemd(&out, ""); err != nil {
		t.Fatal(err)
	}
	got := out.String()
	for _, line := range []string{
		"# rest-named.com.service, generated by `rest -f site.rest -e systemd`\n",
		"WorkingDirectory=/var/www/named.com\n",
		"ExecStart=/usr/local/bin/rest -f site.rest -s",
	} {
		if !strings.Contains(got, line) {
			t.Errorf("missing %q in:\n%s", line, got)
		}
	}
	// --name wins over the server block
	out.Reset()
	if err := r.ExportSystemd(&out, "flag.com"); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out.String(), "WorkingDirectory=/var/www/flag.com\n") {
		t.Errorf("--name didn't override server.name:\n%s", out.String())
	}

	// and it's the openapi title
	out.Reset()
	if err := r.ExportTo(&out, "openapi", "", -1); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out.String(), `"title": "named.com"`) {
		t.Errorf("openapi title isn't server.name:\n%s", out.String())
	}
}

func TestSystemdExportNoServer(t *testing.T) {
	p := writeRest(t, "client.rest", `request "a" { url = "http://localhost" }`)
	r, err := rest.NewFile(p)
	if err != nil {
		t.Fatal(err)
	}
	if err := r.ExportSystemd(&bytes.Buffer{}, ""); err == nil {
		t.Error("expected an error for a file w/o a server block")
	}
}

func TestSiteName(t *testing.T) {
	for in, want := range map[string]string{
		"taybart.com.rest":       "taybart.com",
		"a/b/midnight-lang.rest": "midnight-lang",
		"/abs/path/site":         "site",
	} {
		if got := exports.SiteName(in); got != want {
			t.Errorf("SiteName(%q) = %q, want %q", in, got, want)
		}
	}
}
