package exports_test

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/taybart/rest"
	"github.com/taybart/rest/exports"
)

func writeRest(t *testing.T, dir, name, src string) string {
	t.Helper()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	p := filepath.Join(dir, name)
	if err := os.WriteFile(p, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

func TestSystemdExport(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "midnight-lang.rest")
	p := writeRest(t, dir, "midnight-lang.rest", `server { address = "localhost:8083" }`)
	r, err := rest.NewFile(p)
	if err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer
	if err := r.ExportTo(&out, "systemd", "", -1); err != nil {
		t.Fatal(err)
	}
	got := out.String()
	for _, line := range []string{
		"# rest@.service, generated by `rest -e systemd`\n",
		"enable --now rest@midnight-lang.rest\n", // the folder's name
		"Description=rest server: %i\n",
		"WorkingDirectory=/var/www/%i\n",
		"ExecStart=/usr/local/bin/rest -s -f . --no-color\n",
		"WantedBy=multi-user.target\n",
	} {
		if !strings.Contains(got, line) {
			t.Errorf("missing %q in:\n%s", line, got)
		}
	}
}

func TestSystemdExportServerName(t *testing.T) {
	p := writeRest(t, t.TempDir(), "site.rest", `server {
  name    = "named.com"
  address = "localhost:8083"
}`)
	r, err := rest.NewFile(p)
	if err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer
	if err := r.ExportSystemd(&out); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out.String(), "enable --now rest@named.com\n") {
		t.Errorf("install comment doesn't use server.name:\n%s", out.String())
	}

	// and it's the openapi title
	out.Reset()
	if err := r.ExportTo(&out, "openapi", "", -1); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out.String(), `"title": "named.com"`) {
		t.Errorf("openapi title isn't server.name:\n%s", out.String())
	}
}

func TestSystemdExportNoServer(t *testing.T) {
	p := writeRest(t, t.TempDir(), "client.rest", `request "a" { url = "http://localhost" }`)
	r, err := rest.NewFile(p)
	if err != nil {
		t.Fatal(err)
	}
	if err := r.ExportSystemd(&bytes.Buffer{}); err == nil {
		t.Error("expected an error for a file w/o a server block")
	}
}

func TestSystemdNoFile(t *testing.T) {
	var out bytes.Buffer
	if err := exports.ToSystemd(&out, ""); err != nil {
		t.Fatal(err)
	}
	for _, line := range []string{
		"enable --now rest@<site>\n",
		"WorkingDirectory=/var/www/%i\n",
	} {
		if !strings.Contains(out.String(), line) {
			t.Errorf("missing %q in:\n%s", line, out.String())
		}
	}
}

func TestSiteName(t *testing.T) {
	for in, want := range map[string]string{
		"/var/www/taybart.com/taybart.com.rest":          "taybart.com",
		"/var/www/midnight-lang.rest/midnight-lang.rest": "midnight-lang.rest",
		"/srv/whatever/site.rest":                        "whatever",
	} {
		if got := exports.SiteName(in); got != want {
			t.Errorf("SiteName(%q) = %q, want %q", in, got, want)
		}
	}
}
