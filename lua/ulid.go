func NewULID() string {
	return NewULIDAt(uint64(time.Now().UnixMilli()))
}

func NewULIDAt(ms uint64) string {
	var rnd [10]byte
	_, _ = rand.Read(rnd[:])

	var dst [26]byte
	dst[0] = ulidEncoding[(ms>>45)&0x1F]
	dst[1] = ulidEncoding[(ms>>40)&0x1F]
	dst[2] = ulidEncoding[(ms>>35)&0x1F]
	dst[3] = ulidEncoding[(ms>>30)&0x1F]
	dst[4] = ulidEncoding[(ms>>25)&0x1F]
	dst[5] = ulidEncoding[(ms>>20)&0x1F]
	dst[6] = ulidEncoding[(ms>>15)&0x1F]
	dst[7] = ulidEncoding[(ms>>10)&0x1F]
	dst[8] = ulidEncoding[(ms>>5)&0x1F]
	dst[9] = ulidEncoding[ms&0x1F]

	dst[10] = ulidEncoding[(rnd[0]&248)>>3]
	dst[11] = ulidEncoding[((rnd[0]&7)<<2)|((rnd[1]&192)>>6)]
	dst[12] = ulidEncoding[(rnd[1]&62)>>1]
	dst[13] = ulidEncoding[((rnd[1]&1)<<4)|((rnd[2]&240)>>4)]
	dst[14] = ulidEncoding[((rnd[2]&15)<<1)|((rnd[3]&128)>>7)]
	dst[15] = ulidEncoding[(rnd[3]&124)>>2]
	dst[16] = ulidEncoding[((rnd[3]&3)<<3)|((rnd[4]&224)>>5)]
	dst[17] = ulidEncoding[rnd[4]&31]

	dst[18] = ulidEncoding[(rnd[5]&248)>>3]
	dst[19] = ulidEncoding[((rnd[5]&7)<<2)|((rnd[6]&192)>>6)]
	dst[20] = ulidEncoding[(rnd[6]&62)>>1]
	dst[21] = ulidEncoding[((rnd[6]&1)<<4)|((rnd[7]&240)>>4)]
	dst[22] = ulidEncoding[((rnd[7]&15)<<1)|((rnd[8]&128)>>7)]
	dst[23] = ulidEncoding[(rnd[8]&124)>>2]
	dst[24] = ulidEncoding[((rnd[8]&3)<<3)|((rnd[9]&224)>>5)]
	dst[25] = ulidEncoding[rnd[9]&31]

	return string(dst[:])
}

func IsULID(s string) bool {
	if len(s) != 26 || s[0] > '7' {
		return false
	}
	for i := 0; i < 26; i++ {
		if ulidDec[s[i]] == 0xFF {
			return false
		}
	}
	return true
}

func ULIDTimestamp(s string) (int64, bool) {
	if !IsULID(s) {
		return 0, false
	}
	var ms uint64
	for i := 0; i < 10; i++ {
		ms = (ms << 5) | uint64(ulidDec[s[i]])
	}
	return int64(ms), true
}

func registerULIDModule(l *lua.LState) {
	mod := l.SetFuncs(l.NewTable(), map[string]lua.LGFunction{
		"new":       ulidNew,
		"is_ulid":   ulidIsULID,
		"timestamp": ulidTimestamp,
	})
	mt := l.NewTable()
	l.SetField(mt, "__call", l.NewFunction(func(l *lua.LState) int {
		l.Remove(1) // remove table self
		return ulidNew(l)
	}))
	l.SetMetatable(mod, mt)
	l.SetGlobal("ulid", mod)
}

func ulidNew(l *lua.LState) int {
	if l.GetTop() >= 1 && l.Get(1) != lua.LNil {
		ms := l.CheckInt64(1)
		l.Push(lua.LString(NewULIDAt(uint64(ms))))
		return 1
	}
	l.Push(lua.LString(NewULID()))
	return 1
}

func ulidIsULID(l *lua.LState) int {
	s := l.OptString(1, "")
	l.Push(lua.LBool(IsULID(s)))
	return 1
}

func ulidTimestamp(l *lua.LState) int {
	s := l.CheckString(1)
	ts, ok := ULIDTimestamp(s)
	if !ok {
		l.RaiseError("ulid.timestamp: invalid ulid %q", s)
		return 0
	}
	l.Push(lua.LNumber(ts))
	return 1
}
